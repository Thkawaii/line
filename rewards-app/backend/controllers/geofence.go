// earthRadiusMeters รัศมีเฉลี่ยของโลก ใช้กับสูตรฮาเวอร์ไซน์
const earthRadiusMeters = 6371000.0

// DistanceMeters คืนระยะห่างระหว่างสองพิกัดเป็นเมตร
//
// ใช้สูตรฮาเวอร์ไซน์ซึ่งคิดความโค้งของโลกด้วย ระยะไม่กี่ร้อยเมตรจะคลาดเคลื่อน
// ไม่ถึงหนึ่งเมตร แม่นพอสำหรับการตรวจพื้นที่จัดงาน
func DistanceMeters(lat1, lng1, lat2, lng2 float64) float64 {
	toRad := func(degree float64) float64 { return degree * math.Pi / 180 }

	dLat := toRad(lat2 - lat1)
	dLng := toRad(lng2 - lng1)

	a := math.Sin(dLat/2)*math.Sin(dLat/2) +
		math.Cos(toRad(lat1))*math.Cos(toRad(lat2))*
			math.Sin(dLng/2)*math.Sin(dLng/2)

	return earthRadiusMeters * 2 * math.Atan2(math.Sqrt(a), math.Sqrt(1-a))
}

