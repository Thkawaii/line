-- 013 — ย้ายเวลาขึ้นแบบประเมินมาอยู่ที่ตัวกิจกรรม และเปลี่ยนหน่วยเป็นนาที

/*
เดิมตั้งเป็นค่ากลางของทั้งระบบ หน่วยเป็นชั่วโมง (event.feedbackLeadHours)

ปัญหาคือกิจกรรมแต่ละงานยาวไม่เท่ากัน งานอบรมทั้งวันกับงานประชุมสั้น 30 นาที
ใช้เวลาเดียวกันไม่ได้ ค่ากลางหนึ่งชั่วโมงแปลว่างานที่สั้นกว่าหนึ่งชั่วโมง
จะขึ้นแบบประเมินตั้งแต่ก่อนงานเริ่ม

หน่วยชั่วโมงเองก็หยาบเกินไปสำหรับงานสั้น ต้องการ "ก่อนจบ 10 นาที" แต่กรอกได้
แค่จำนวนเต็มชั่วโมง เก็บเป็นนาทีหน่วยเดียวจึงครอบคลุมทั้งสองแบบ
หน้าเว็บจะให้เลือกกรอกเป็นนาทีหรือชั่วโมงก็ได้ แล้วแปลงเป็นนาทีก่อนส่งมา
*/

ALTER TABLE events
  ADD COLUMN IF NOT EXISTS feedback_lead_minutes INTEGER NOT NULL DEFAULT 60;

/*
ยกค่าเดิมจากค่ากลางมาใส่ให้ทุกกิจกรรมที่มีอยู่แล้ว

ถ้าตั้งไว้ 2 ชั่วโมง กิจกรรมเก่าทุกงานต้องได้ 120 นาที
ไม่ใช่กลับไปเป็นค่าเริ่มต้น 60 นาที ไม่งั้นพฤติกรรมของงานที่ตั้งไว้แล้วจะเปลี่ยนเอง
โดยที่ผู้ดูแลไม่ได้สั่ง

เช็ค ~ '^[0-9]+$' ก่อนแปลงชนิด เผื่อค่าในตารางถูกแก้เป็นอย่างอื่นไว้
ถ้าแปลงไม่ได้ก็ปล่อยให้ใช้ค่าเริ่มต้น ดีกว่าให้ไมเกรชันพัง
*/
UPDATE events e
SET feedback_lead_minutes = sub.minutes
FROM (
  -- ค่าเดิมเป็นชั่วโมง ของเดิมจำกัดไว้ 0 ถึง 720 ชั่วโมง (30 วัน) คูณ 60 ได้ 43,200 นาที
  SELECT LEAST(GREATEST(value::int, 0), 720) * 60 AS minutes
  FROM settings
  WHERE key = 'event.feedbackLeadHours' AND value ~ '^[0-9]+$'
) AS sub
WHERE e.feedback_lead_minutes = 60;

-- ค่ากลางไม่ใช้แล้ว ลบออกจากหน้าตั้งค่าระบบ ไม่งั้นจะมีช่องที่กรอกไปก็ไม่มีผล
DELETE FROM settings WHERE key = 'event.feedbackLeadHours';
