-- 012 — เด้งแจ้งพนักงานเมื่อคะแนนถูกปรับ
--
-- เดิมคะแนนที่ถูกปรับด้วยมือเปลี่ยนไปเงียบ ๆ พนักงานรู้ตัวอีกทีตอนเปิดดูยอด
-- แล้วไม่รู้ว่าทำไมถึงเปลี่ยน ใครเป็นคนทำ และด้วยเหตุผลอะไร
--
-- alerted_at คือเวลาที่พนักงานกดรับทราบป็อปอัป ไม่ใช่เวลาที่ส่ง
-- เก็บแบบนี้เพราะต้องรู้ว่า "ยังไม่ได้เห็น" ไม่ใช่ "ส่งไปแล้ว"
-- พนักงานที่ไม่ได้เปิดแอปหลายวันต้องยังได้เห็นตอนเปิดครั้งถัดไป
--
-- ว่างอยู่ = ยังไม่ได้กดรับทราบ จึงยังต้องเด้ง

ALTER TABLE point_transactions ADD COLUMN IF NOT EXISTS alerted_at TIMESTAMPTZ;

/*
  รายการเก่าที่เกิดก่อนมีระบบนี้ ถือว่ารับทราบไปแล้ว

  ไม่งั้นพนักงานที่เคยถูกปรับคะแนนมาก่อนจะโดนป็อปอัปย้อนหลังรัวติดกัน
  ตอนเปิดแอปครั้งแรกหลังอัปเดต ซึ่งน่ารำคาญและไม่มีประโยชน์
  เพราะเรื่องผ่านไปนานแล้ว
*/
UPDATE point_transactions SET alerted_at = now()
WHERE alerted_at IS NULL AND kind = 'adjust';

-- เทมเพลตแจ้งเตือน ปิดแยกได้ที่แท็บ Systems Event
INSERT INTO notification_events (key, name, description, in_app, email, active, sort_order) VALUES
  ('point_adjusted','คะแนนถูกปรับ',
   'แจ้งพนักงานเมื่อคะแนนของตัวเองถูกปรับจากคำขอที่อนุมัติแล้ว',true,false,true,9)
ON CONFLICT (key) DO NOTHING;
