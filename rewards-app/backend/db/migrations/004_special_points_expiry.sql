-- 004 — วันหมดอายุของคะแนนพิเศษ
--
-- คะแนนพิเศษเป็นรางวัลเฉพาะกิจ จึงควรมีอายุ ไม่ใช่สะสมค้างไว้ตลอดไป
-- ถึงวันหมดอายุแล้วยอดจะถูกตัดเหลือ 0 พร้อมบันทึกรายการเดินบัญชีไว้ให้ตรวจสอบได้
--
-- เก็บวันหมดอายุไว้ที่ผู้ใช้หนึ่งค่า ไม่ได้แยกรายก้อน
-- ถ้าได้คะแนนพิเศษก้อนใหม่ที่มีวันหมดอายุไกลกว่าเดิม ระบบจะเลื่อนวันหมดอายุออกไป
-- เพราะพนักงานไม่ควรเสียคะแนนก้อนใหม่เพราะก้อนเก่าใกล้หมดอายุ

ALTER TABLE users  ADD COLUMN IF NOT EXISTS special_points_expire_at DATE;
ALTER TABLE events ADD COLUMN IF NOT EXISTS special_points_expire_at DATE;
