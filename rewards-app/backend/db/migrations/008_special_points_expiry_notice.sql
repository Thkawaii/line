-- 008 — แจ้งเตือนล่วงหน้าก่อนคะแนนพิเศษหมดอายุ
--
-- เดิมคะแนนพิเศษถูกตัดเหลือ 0 เงียบ ๆ ตอนพ้นวันหมดอายุ พนักงานรู้ตัวอีกทีก็สายแล้ว
-- ต่อไปนี้ระบบจะส่งแจ้งเตือนล่วงหน้าตามค่า expire_warn_days ในหน้าตั้งค่า
--
-- special_points_notified_for เก็บ "วันหมดอายุที่เคยเตือนไปแล้ว" ไม่ใช่เวลาที่เตือน
-- เพราะตัวตั้งเวลาวิ่งทุกชั่วโมง ถ้าไม่จดไว้พนักงานจะโดนเตือนซ้ำวันละ 24 รอบ
-- และถ้าได้คะแนนพิเศษก้อนใหม่ที่เลื่อนวันหมดอายุออกไป ค่านี้จะไม่ตรงกับวันใหม่
-- รอบถัดไปจึงเตือนให้ใหม่ได้เองโดยไม่ต้องล้างค่าทิ้ง

ALTER TABLE users ADD COLUMN IF NOT EXISTS special_points_notified_for DATE;

-- เทมเพลตแจ้งเตือนของตัวเอง แยกจาก points_expiring ที่เป็นของคะแนนปกติ
-- ผู้ดูแลจึงปิดเฉพาะอันนี้ได้โดยไม่กระทบอีกอัน
INSERT INTO notification_events (key, name, description, in_app, email, active, sort_order) VALUES
  ('special_points_expiring','คะแนนพิเศษใกล้หมดอายุ',
   'แจ้งเตือนพนักงานล่วงหน้าก่อนคะแนนพิเศษถูกตัดเหลือ 0',true,false,true,6)
ON CONFLICT (key) DO NOTHING;
