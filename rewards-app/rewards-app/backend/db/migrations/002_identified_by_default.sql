-- 002 — หัวข้อใหม่เห็นชื่อผู้ตอบเป็นค่าเริ่มต้น
--
-- เดิมตั้งค่าเริ่มต้นเป็น "ไม่ระบุตัวตน" แต่เจ้าของระบบยืนยันว่าฝ่ายธุรการและ
-- ผู้ดูแลระบบต้องเห็นชื่อ เพื่อติดตามว่าใครยังไม่ได้ลงทะเบียนในแต่ละกิจกรรม
--
-- เปลี่ยนเฉพาะค่าตั้งต้นของหัวข้อที่จะสร้างใหม่เท่านั้น
-- หัวข้อเดิมที่ตั้งไม่ระบุตัวตนไว้ยังคงเป็นแบบนั้นต่อไป เพราะพนักงานที่ตอบไปแล้ว
-- เห็นข้อความรับปากไว้บนหน้าจอก่อนกดส่ง การย้อนกลับไปเปิดเผยจึงทำไม่ได้

